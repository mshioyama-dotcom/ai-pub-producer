// 文字列の頭に見出しが既にあれば付け足さない（STEP0等のAI出力に既に見出しが含まれるため）
function withHeading(text, heading) {
  const t = (text || "").trim();
  if (!t) return `${heading}\n\n（未登録）`;
  // 既に同じ見出しで始まっていれば、そのまま使う
  if (t.startsWith(heading)) return t;
  return `${heading}\n\n${t}`;
}

